#!/usr/bin/env node
/* Build the browser bundle from the checked-in LRC files (no fetch needed at runtime). */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'lyrics');
const files = fs.readdirSync(dir).filter(name => name.endsWith('.lrc')).sort();
const data = {};

for (const file of files) {
  const cues = [];
  for (const line of fs.readFileSync(path.join(dir, file), 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\[(\d+):(\d{2}(?:\.\d+)?)\](.*)$/);
    if (!match) continue;
    const time = Math.round((Number(match[1]) * 60 + Number(match[2])) * 1000) / 1000;
    if (cues.length && time < cues[cues.length - 1].time) {
      throw new Error(`${file}: timestamps are not ordered at ${line}`);
    }
    cues.push({ time, text: match[3].trim() });
  }
  if (!cues.some(cue => cue.text)) throw new Error(`${file}: no timed text`);
  data[path.basename(file, '.lrc')] = cues;
}
if (files.length !== 8) throw new Error(`Expected 8 LRC files, found ${files.length}`);
const output = `/* Generated by node scripts/build-lyrics.js from lyrics/*.lrc. */\nwindow.LYRICS_DATA = ${JSON.stringify(data, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'lyrics.js'), output);
console.log(`Built lyrics.js from ${files.length} LRC files.`);
